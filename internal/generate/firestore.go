const header = "// Generated by FQL. DO NOT EDIT.\n"

func quoted(s string) string { b, _ := json.Marshal(s); return string(b) }
func literal(v schema.Value, t string, dart bool) string {
	if v.Kind == "null" {
		return "null"
	}
	if t == "timestamp" {
		d, _ := time.Parse(time.RFC3339Nano, v.Text)
		if dart {
			return "Timestamp.fromDate(DateTime.parse(" + dartString(d.UTC().Format(time.RFC3339Nano)) + ").toUtc())"
		}
		return fmt.Sprintf("timestamp.value(%d) + duration.value(%d, 'ns')", d.UnixMilli(), (d.Nanosecond()/1000%1000)*1000)
	}
	if t == "date" && dart {
		return "FqlDate.parse(" + dartString(v.Text) + ")"
	}
	if v.Kind == "string" {
		if dart {
			return dartString(v.Text)
		}
		return quoted(v.Text)
	}
	if t == "float" {
		n, _ := strconv.ParseFloat(v.Text, 64)
		format := byte('f')
		if dart {
			format = 'g'
		}
		value := strconv.FormatFloat(n, format, -1, 64)
		if dart && !strings.ContainsAny(value, ".eE") {
			value += ".0"
		}
		return value
	}
	return v.Text
}
func rulesCondition(f schema.Field) string {
	return rulesValue(f, "d["+quoted(f.Name)+"]", "d")
}
func rulesValue(f schema.Field, v, container string) string {
	parts := []string{}
	switch f.Type {
	case "list":
		parts = append(parts, v+" is list", fmt.Sprintf("%s.size() <= %d", v, *f.MaxItems))
		if f.MinItems != nil {
			parts = append(parts, fmt.Sprintf("%s.size() >= %d", v, *f.MinItems))
		}
		for i := 0; i < *f.MaxItems; i++ {
			parts = append(parts, fmt.Sprintf("(%s.size() <= %d || %s)", v, i, rulesValue(*f.ElementField, fmt.Sprintf("%s[%d]", v, i), "")))
		}
	default:
		if len(f.EnumValues) > 0 {
			var values []string
			for _, x := range f.EnumValues {
				values = append(values, quoted(x))
			}
			parts = append(parts, v+" is string", v+" in ["+strings.Join(values, ", ")+"]")
		} else if len(f.ObjectFields) > 0 {
			var names, required []string
			for _, x := range f.ObjectFields {
				names = append(names, quoted(x.Name))
				if !x.Optional {
					required = append(required, quoted(x.Name))
				}
			}
			parts = append(parts, v+" is map", v+".keys().hasOnly(["+strings.Join(names, ", ")+"])", v+".keys().hasAll(["+strings.Join(required, ", ")+"])")
			for _, x := range f.ObjectFields {
				parts = append(parts, rulesValue(x, v+"["+quoted(x.Name)+"]", v))
			}
		}
	case "string":
		parts = append(parts, v+" is string", v+".toUtf8().size() <= 1048487")
	case "bool":
		parts = append(parts, v+" is bool")
	case "int":
		parts = append(parts, v+" is int", v+" >= -9007199254740991", v+" <= 9007199254740991")
	case "float":
		parts = append(parts, "("+v+" is float || "+v+" is int)", v+" >= -9007199254740991", v+" <= 9007199254740991")
	case "date":
		parts = append(parts, v+" is string", v+".matches('[0-9]{4}-[0-9]{2}-[0-9]{2}')", "validDate("+v+")")
	case "timestamp":
		parts = append(parts, v+" is timestamp", v+".year() >= 1", v+".year() <= 9999", v+".nanos() % 1000 == 0")
	}
	if f.MinLength != nil {
		parts = append(parts, fmt.Sprintf("%s.toUtf8().size() >= %d", v, *f.MinLength))
	}
	if f.MaxLength != nil {
		parts = append(parts, fmt.Sprintf("%s.toUtf8().size() <= %d", v, *f.MaxLength))
	}
	if f.Min != nil {
		parts = append(parts, fmt.Sprintf("%s >= %s", v, strconv.FormatFloat(*f.Min, 'f', -1, 64)))
	}
	if f.Max != nil {
		parts = append(parts, fmt.Sprintf("%s <= %s", v, strconv.FormatFloat(*f.Max, 'f', -1, 64)))
	}
	if len(f.Allowed) > 0 {
		var allowed []string
		for _, x := range f.Allowed {
			allowed = append(allowed, literal(x, f.Type, false))
		}
		parts = append(parts, v+" in ["+strings.Join(allowed, ", ")+"]")
	}
	c := "(" + strings.Join(parts, " && ") + ")"
	if f.Nullable {
		c = "(" + v + " == null || " + c + ")"
	}
	if f.Optional {
		c = "(!(" + quoted(f.Name) + " in " + container + ") || " + c + ")"
	}
	return c
}
func policy(m schema.Model, op string) string {
	for _, a := range m.Policies {
		if a.Operation != op {
			continue
		}
		switch a.Kind {
		case "authenticated":
			return "request.auth != null"
		case "owner":
			if a.Field == "id" {
				return "request.auth != null && request.auth.uid == documentId"
			}
			prefix := "resource"
			if op == "create" {
				prefix = "request.resource"
			}
			return "request.auth != null && " + prefix + ".data[" + quoted(a.Field) + "] == request.auth.uid"
		}
	}
	return "false"
}

// Firestore renders complete, default-deny rules and explicit index configuration.
func Firestore(s schema.Schema) ([]byte, []byte, error) {
	var b strings.Builder
	b.WriteString(header + `rules_version = '2';
service cloud.firestore {
  match /databases/{database}/documents {
    function validDate(v) {
      let p = v.split('-');
      let y = int(p[0]);
      let m = int(p[1]);
      let d = int(p[2]);
      let leap = y % 4 == 0 && (y % 100 != 0 || y % 400 == 0);
      let days = m == 2 ? (leap ? 29 : 28) : (m in [4, 6, 9, 11] ? 30 : 31);
      return y >= 1 && y <= 9999 && m >= 1 && m <= 12 && d >= 1 && d <= days;
    }
`)
	type indexField struct {
		FieldPath string `json:"fieldPath"`
		Order     string `json:"order"`
	}
	type index struct {
		CollectionGroup string       `json:"collectionGroup"`
		QueryScope      string       `json:"queryScope"`
		Fields          []indexField `json:"fields"`
	}
	indexes := []index{}
	for _, m := range s.Models {
		fmt.Fprintf(&b, "    match /%s/{documentId} {\n      function valid(d) {\n", m.Collection)
		var names, required, immutable, conditions, created, updated []string
		for _, f := range m.Fields {
			names = append(names, quoted(f.Name))
			if !f.Optional {
				required = append(required, quoted(f.Name))
			}
			if f.Immutable {
				immutable = append(immutable, quoted(f.Name))
			}
			conditions = append(conditions, rulesCondition(f))
			if f.Server != "" {
				created = append(created, "request.resource.data["+quoted(f.Name)+"] == request.time")
				if f.Server == "serverUpdated" {
					updated = append(updated, "request.resource.data["+quoted(f.Name)+"] == request.time")
				}
			}
		}
		fmt.Fprintf(&b, "        return d.keys().hasOnly([%s]) && d.keys().hasAll([%s])\n          && %s;\n      }\n", strings.Join(names, ", "), strings.Join(required, ", "), strings.Join(conditions, "\n          && "))
		fmt.Fprintf(&b, "      allow read: if %s;\n      allow create: if (%s) && valid(request.resource.data);\n      allow update: if (%s) && valid(request.resource.data) && !request.resource.data.diff(resource.data).affectedKeys().hasAny([%s]);\n      allow delete: if %s;\n    }\n", policy(m, "read"), withConditions(policy(m, "create"), created), withConditions(policy(m, "update"), updated), strings.Join(immutable, ", "), policy(m, "delete"))
		for _, idx := range m.Indexes {
			i := index{CollectionGroup: m.Collection, QueryScope: "COLLECTION"}
			for _, f := range idx {
				order := "ASCENDING"
				if f.Direction == "desc" {
					order = "DESCENDING"
				}
				i.Fields = append(i.Fields, indexField{FieldPath: f.Name, Order: order})
			}
			indexes = append(indexes, i)
		}
	}
	b.WriteString("  }\n}\n")
	indexJSON, e := json.MarshalIndent(struct {
		Indexes        []index `json:"indexes"`
		FieldOverrides []any   `json:"fieldOverrides"`
	}{indexes, []any{}}, "", "  ")
	return []byte(b.String()), append(indexJSON, '\n'), e
}

func withConditions(policy string, conditions []string) string {
	for _, c := range conditions {
		policy += " && " + c
	}
	return policy
}
